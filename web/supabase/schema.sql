-- =============================================================================
-- HELPER: Full-text search function (used by Epic 5 discoverability layer)
-- =============================================================================
-- Usage: SELECT * FROM search_sermons('prayer faith');
CREATE OR REPLACE FUNCTION public.search_sermons(query TEXT)
RETURNS SETOF public.sermons
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT *
  FROM public.sermons
  WHERE
    to_tsvector('english', COALESCE(transcript_text, '')) @@ plainto_tsquery('english', query)
    OR to_tsvector('english', title) @@ plainto_tsquery('english', query)
  ORDER BY
    ts_rank(
      to_tsvector('english', COALESCE(transcript_text, '') || ' ' || title),
      plainto_tsquery('english', query)
    ) DESC;
$$;

